/**
 * Turns the CSL style files into modules the app can import lazily.
 *
 * The `.csl` files in `src/lib/citation/styles/` are the official styles from
 * the Citation Style Language repository, kept unmodified so they can be
 * updated by dropping in a newer copy. The browser needs them as strings, and
 * a generated module per style lets the bundler split each one into its own
 * chunk that loads only when a student picks that style — no raw-file loader
 * or extra dependency required.
 *
 * Run after replacing a style file:
 *
 *   npm run styles
 *
 * A unit test fails if a generated module no longer matches its source.
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { CSL_SOURCES, minifyCsl } from "../src/lib/citation/styles/minify.ts";

const dir = fileURLToPath(new URL("../src/lib/citation/styles/", import.meta.url));
await mkdir(`${dir}generated`, { recursive: true });

for (const [id, file] of Object.entries(CSL_SOURCES)) {
  const xml = minifyCsl(await readFile(`${dir}${file}`, "utf8"));
  const title = /<title>([^<]*)<\/title>/.exec(xml)?.[1] ?? file;
  const body = [
    `// Generated by \`npm run styles\` from ${file}. Do not edit by hand.`,
    `// ${title}. CC BY-SA 3.0, from the Citation Style Language project.`,
    `const style = ${JSON.stringify(xml)};`,
    "export default style;",
    "",
  ].join("\n");
  await writeFile(`${dir}generated/${id}.ts`, body);
  console.log(`${id.padEnd(8)} ${(xml.length / 1024).toFixed(1).padStart(6)} KB  ${title}`);
}
